/**
 * Normalises a display name: NFC (so Vietnamese diacritics stay single characters),
 * letters / digits / space / `._-` only, collapsed whitespace, at most 16 characters.
 * Returns null when nothing usable is left.
 */
export function sanitizeName(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const cleaned = raw
    .normalize("NFC")
    .replace(/\s+/g, " ")
    .replace(/[^\p{L}\p{M}\p{N} ._-]/gu, "")
    .replace(/ {2,}/g, " ")
    .trim();
  const name = Array.from(cleaned).slice(0, NAME_MAX_LENGTH).join("").trim();
  return /[\p{L}\p{N}]/u.test(name) ? name : null;
}

/** Player ids are 128-bit random hex strings generated by the browser. */
export function isPlayerId(value: unknown): value is string {
  return typeof value === "string" && /^[a-f0-9]{32}$/.test(value);
}

const isCount = (n: unknown): n is number => Number.isSafeInteger(n) && (n as number) >= 0;

/** Most team goals a match of this length can hold (each goal cycle takes MIN_MS_PER_GOAL). */
export const maxGoalsFor = (durationMs: number) => Math.floor(durationMs / MIN_MS_PER_GOAL) + 1;

/**
 * Sanity checks a match against the game's rules. It can't make a browser game
 * cheat-proof, but it bounds goals and assists by real playing time (the
 * duration itself is checked against a server-signed start time).
 */
export function checkMatch(m: MatchStats, matchSeconds = MATCH_SECONDS): "implausible_match" | null {
  if (![m.goals, m.assists, m.durationMs].every(isCount)) return "implausible_match";
  if (m.durationMs > matchSeconds * 1000 + CLOCK_SLACK_MS) return "implausible_match";
  // every goal and assist belongs to a different team goal
  if (m.goals + m.assists > maxGoalsFor(m.durationMs)) return "implausible_match";
  return null;
}

/** Bonus for scoring exactly two (brace) or three or more (hat-trick). */
export const multiGoalBonus = (goals: number) =>
  goals >= 3 ? HAT_TRICK_BONUS : goals === 2 ? BRACE_BONUS : 0;

/** GOAT points for one match, with the trophies it earned on its career stage. */
export function scoreMatch(goals: number, assists: number, outcome: StageOutcome | null): number {
  return (
    goals * GOAL_POINTS +
    assists * ASSIST_POINTS +
    multiGoalBonus(goals) +
    (outcome?.trophy ? TROPHY_POINTS : 0) +
    (outcome?.ballonDor ? BALLON_DOR_POINTS : 0)
  );
}

/** Stage outcome of a submitted match, or null for quick matches / unknown stages. */
export function outcomeOf(req: Pick<SubmitRequest, "mode" | "stageId" | "hero" | "goals" | "assists">) {
  if (req.mode !== "career") return null;
  const stage = findStage(req.stageId);
  if (!stage || stage.hero !== req.hero) return null;
  return evaluateStage(stage, req.goals, req.assists);
}

/** Totals a single hero's match adds to the Legacy board. */
export function totalsDelta(goals: number, assists: number, outcome: StageOutcome | null, won: boolean) {
  const d = emptyTotals();
  d.matches = 1;
  d.goals = goals;
  d.assists = assists;
  d.braces = goals === 2 ? 1 : 0;
  d.hatTricks = goals >= 3 ? 1 : 0;
  d.wins = won ? 1 : 0;
  if (outcome?.trophy) {
    d.trophies = 1;
    if (outcome.trophy === "ucl") d.ucl = 1;
    if (outcome.trophy === "worldcup") d.worldcup = 1;
  }
  if (outcome?.ballonDor) {
    d.ballonDor = 1;
    d.trophies += 1;
  }
  return d;
}

function record(body: unknown): Record<string, unknown> | null {
  return typeof body === "object" && body !== null && !Array.isArray(body)
    ? (body as Record<string, unknown>)
    : null;
}

/** Validates an untrusted JSON body for POST /api/leaderboard. */
export function parseSubmitRequest(body: unknown): SubmitRequest | null {
  const b = record(body);
  if (!b) return null;
  if (!["goals", "assists", "durationMs"].every((k) => typeof b[k] === "number")) return null;
  if (typeof b.playerId !== "string" || typeof b.name !== "string" || typeof b.token !== "string") {
    return null;
  }
  if (!isHeroId(b.hero) || (b.mode !== "career" && b.mode !== "quick")) return null;
  if (b.stageId !== undefined && b.stageId !== null && typeof b.stageId !== "string") return null;
  return {
    playerId: b.playerId,
    name: b.name,
    token: b.token,
    hero: b.hero,
    mode: b.mode,
    stageId: (b.stageId as string | null | undefined) ?? null,
    goals: b.goals as number,
    assists: b.assists as number,
    durationMs: b.durationMs as number,
  };
}

/** Validates an untrusted JSON body for POST /api/rivalry. */
export function parseRivalryRequest(body: unknown): RivalryRequest | null {
  const b = record(body);
  if (!b || typeof b.token !== "string" || typeof b.durationMs !== "number") return null;
  const side = (v: unknown) => {
    const r = record(v);
    return r && typeof r.goals === "number" && typeof r.assists === "number"
      ? { goals: r.goals, assists: r.assists }
      : null;
  };
  const cr7 = side(b.cr7);
  const lm10 = side(b.lm10);
  if (!cr7 || !lm10) return null;
  return { token: b.token, durationMs: b.durationMs, cr7, lm10 };
}

/** A PvP match: both heroes share one clock, so their goals share the bound. */
export function checkRivalry(r: RivalryRequest): "implausible_match" | null {
  const stats = [r.cr7.goals, r.cr7.assists, r.lm10.goals, r.lm10.assists, r.durationMs];
  if (!stats.every(isCount)) return "implausible_match";
  if (r.durationMs > PVP_SECONDS * 1000 + CLOCK_SLACK_MS) return "implausible_match";
  const total = r.cr7.goals + r.cr7.assists + r.lm10.goals + r.lm10.assists;
  if (total > maxGoalsFor(r.durationMs)) return "implausible_match";
  return null;
}

/** PvP Rivalry "carry index" (chỉ số gánh team): who carried their side harder. */
export const carryIndex = (s: { goals: number; assists: number }) => s.goals * 3 + s.assists * 2;
