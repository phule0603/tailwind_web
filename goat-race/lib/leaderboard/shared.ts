/* Types and validation shared by the browser and the API routes. */

export const NAME_MAX_LENGTH = 16;
export const LEADERBOARD_SIZE = 10;
/** the match clock can't run longer than this (plus a little slack for the final frame) */
const CLOCK_SLACK_MS = 1000;

export type MatchMode = "career" | "quick";

export interface MatchStats {
  goals: number;
  assists: number;
  /** game-clock milliseconds actually played */
  durationMs: number;
}

export interface SubmitRequest extends MatchStats {
  playerId: string;
  name: string;
  token: string;
  hero: HeroId;
  mode: MatchMode;
  stageId: string | null;
}

export interface RivalryRequest {
  token: string;
  durationMs: number;
  cr7: { goals: number; assists: number };
  lm10: { goals: number; assists: number };
}

/** Running totals per hero, summed over every match ever played. */
export interface HeroTotals {
  matches: number;
  goals: number;
  assists: number;
  braces: number;
  hatTricks: number;
  trophies: number;
  ballonDor: number;
  ucl: number;
  worldcup: number;
  wins: number;
}

export const TOTAL_KEYS: (keyof HeroTotals)[] = [
  "matches",
  "goals",
  "assists",
  "braces",
  "hatTricks",
  "trophies",
  "ballonDor",
  "ucl",
  "worldcup",
  "wins",
];

export const emptyTotals = (): HeroTotals =>
  Object.fromEntries(TOTAL_KEYS.map((k) => [k, 0])) as unknown as HeroTotals;

